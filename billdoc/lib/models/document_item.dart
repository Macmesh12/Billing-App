class DocumentItem {
  final String id;
  final String customer;
  final String type;
  final String date;
  final String number;
  final String location;
  final double amount;

  DocumentItem({
    required this.id,
    required this.customer,
    required this.type,
    required this.date,
    required this.number,
    required this.location,
    required this.amount,
  });
}
